namespace HomebrewDot.Net.Rimworld.UI
{
    /// <summary>
    /// Represents the data type of a constant value for UI input.
    /// </summary>
    public enum ConstantType
    {
        /// <summary>
        /// Value is a string.
        /// </summary>
        Text,
        /// <summary>
        /// Value is an integer.
        /// </summary>
        Number,
        /// <summary>
        /// Value is a floating point number (double).
        /// </summary>
        Decimal,
    }
}